export function findFranchiseByCodeOrId(identifier) {
  if (!identifier) return null;
  const cleaned = String(identifier).trim().toUpperCase();

  if (cleaned === 'AHILYANAGAR' || cleaned === 'AHMEDNAGAR' || cleaned === 'C5' || cleaned === 'CL16') {
    return MASTER_FRANCHISES.find((f) => f.vistaCinemaId === 'CL16') || null;
  }
  if (cleaned === 'GANDHINAGAR' || cleaned === 'C0' || cleaned === 'ALL') {
    return MASTER_FRANCHISES.find((f) => f.franchiseCode === 'FR-CN02') || null;
  }
  if (cleaned === 'JODHPUR' || cleaned === 'C1') {
    return MASTER_FRANCHISES.find((f) => f.vistaCinemaId === 'CN03') || null;
  }
  if (cleaned === 'JAIPUR' || cleaned === 'C2') {
    return MASTER_FRANCHISES.find((f) => f.vistaCinemaId === 'CN04') || null;
  }
  if (cleaned === 'AHMEDABAD' || cleaned === 'C3') {
    return MASTER_FRANCHISES.find((f) => f.vistaCinemaId === 'CN01') || null;
  }
  if (cleaned === 'UDAIPUR' || cleaned === 'C4') {
    return MASTER_FRANCHISES.find((f) => f.vistaCinemaId === 'CN05') || null;
  }

  const byCode = MASTER_FRANCHISES.find((f) => f.franchiseCode.toUpperCase() === cleaned);
  if (byCode) return byCode;

  const byVistaId = MASTER_FRANCHISES.find((f) => f.vistaCinemaId.toUpperCase() === cleaned);
  if (byVistaId) return byVistaId;

  const byLocKey = MASTER_FRANCHISES.find((f) => f.locationKey.toUpperCase() === cleaned);
  if (byLocKey) return byLocKey;

  const byName = MASTER_FRANCHISES.find((f) => f.name.toUpperCase().includes(cleaned));
  if (byName) return byName;

  return null;
}
